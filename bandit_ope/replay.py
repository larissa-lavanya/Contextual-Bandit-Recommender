"""Unbiased offline replay evaluation of bandit algorithms (Li et al., 2011)."""

from dataclasses import dataclass

import numpy as np

try:
    from tqdm import tqdm
except ImportError:  # progress bars are optional
    tqdm = None


@dataclass
class ReplayResult:
    """Outcome of replaying one algorithm over a log."""

    matched_rewards: np.ndarray  # reward of every round where the algorithm agreed with the log
    n_rounds: int  # number of logged rounds that were streamed

    @property
    def n_matched(self):
        return len(self.matched_rewards)

    @property
    def ctr(self):
        """Estimated click-through rate over the whole run (includes the learning phase)."""
        return float(self.matched_rewards.mean()) if self.n_matched else float("nan")

    @property
    def late_ctr(self):
        """Estimated CTR over the second half of the run, i.e. after most of the learning."""
        half = self.n_matched // 2
        return float(self.matched_rewards[half:].mean()) if self.n_matched else float("nan")

    def running_ctr(self):
        """CTR after each matched round (for learning curves)."""
        return np.cumsum(self.matched_rewards) / np.arange(1, self.n_matched + 1)


def check_uniform_logging(feedback):
    """Replay is only unbiased when the logging policy picked items uniformly at random."""
    if not np.allclose(feedback.pscore, 1.0 / feedback.n_actions, rtol=1e-3):
        raise ValueError("Replay needs logs from the uniform-random behavior policy.")


def replay_evaluate(policy, feedback, max_rounds=None, show_progress=False):
    """Stream the log; keep a round only if the policy picks the item that was logged.

    Because the log was generated by a uniform-random policy, a matched round is a
    fair sample of what would have happened had the algorithm run live.
    """
    check_uniform_logging(feedback)
    n = feedback.n_rounds if max_rounds is None else min(max_rounds, feedback.n_rounds)

    rounds = range(n)
    if show_progress and tqdm is not None:
        rounds = tqdm(rounds, desc=policy.name, leave=False)

    matched_rewards = []
    for t in rounds:
        x = feedback.context[t]

        # The algorithm chooses an item using only what it has seen so far
        chosen = policy.select_action(x)

        # Keep the round only if it agrees with the log, and learn from it
        if chosen == feedback.action[t]:
            reward = feedback.reward[t]
            policy.update(x, chosen, reward)
            matched_rewards.append(reward)

    return ReplayResult(matched_rewards=np.array(matched_rewards), n_rounds=n)
